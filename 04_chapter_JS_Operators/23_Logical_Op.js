// && -> AND Gate
// || -> OR Gate

let a = true;
let b = false;

console.log(a && b);
console.log(a || b);
console.log(!a);

/*
1.Logical AND (&&)

Truth table:
A	    B	        A && B
true	true	true
true	false	false
false	true	false
false	false	false


2.Logical OR (||)

Truth table:
| A     |       B      | A || B |
|    ---|   ---|---    |
| true  | true         | true |
| true  | false        | true |
| false | true         | true |
| false | false        | false |

3.Logical NOT (!)
Truth table:
| A     |       !A      |
|    ---|   ---|---    |
| true  | false        |
| false | true         |    

*/
