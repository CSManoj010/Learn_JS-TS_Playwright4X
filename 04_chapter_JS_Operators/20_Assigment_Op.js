let x = 10;
x = "Manoj"; //assignment operator = 
console.log(x);

let x1 = 10;
x1  = x1 +5; // x1 += 5;  //incremental operator 
console.log(x1);

let x2 = 20;
x2 = x2 - 5; // x2 -= 5;  //decremental operator
console.log(x2);

/* 

Types of assignment operators
    =	    x = 10	Assign 10 to x
    +=	    x += 5	x = x + 5
    -=	    x -= 5	x = x - 5
    *=	    x *= 5	x = x * 5
    /=	    x /= 5	x = x / 5
    %=	    x %= 3	x = x % 3
    **= 	x **= 2	x = x ** 2

*/